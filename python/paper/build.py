r""" Stage (iii) of the paper pipeline: build every table and figure from results/ and copy them into
writing/Paper.

Run:  .venv\Scripts\python.exe python\paper\build.py                 build everything buildable
      ... --only ArgentinaUniversal ARG_CRRA_LOG                     a subset
      ... --no-copy                                                  write results/paper only
      ... --list                                                     what is buildable and what is not
      ... --map                                                      rewrite the output map in REPLICATION.md
      ... --site                                                     write the online appendix from
                                                                     results/paper (onlineAppendix.build)

This stage imports NO model code and unpickles nothing. It reads csv, writes tex and pdf, and takes
seconds -- which is what makes it safe to re-run after every edit to a caption or a rounding rule. The
expensive work belongs to stages (i) and (ii), whose output in results/ is the record.

An output whose inputs are missing is REPORTED AND SKIPPED, never partially written: an experiment that
has not been run must not be able to look like a table that has.

WHERE THINGS LAND. Every output is written to results/paper/ first and then copied into writing/Paper/
(--no-copy stops at the first step), except the online appendix's own exhibits (ONLINE_ONLY), which stay
in results/paper/. The first time a copy would overwrite a file that does not carry
this pipeline's banner -- i.e. the hand-written version still in the repo -- that file is preserved
under results/paper/superseded/ and the takeover is announced. Superseded content never stays beside
live content (notes/crossCuttingFindings.md #8).
"""
