def _copy(src, dest, report):
    """ Copy one built file into writing/Paper, preserving a hand-written predecessor exactly once. """
    os.makedirs(os.path.dirname(dest), exist_ok = True)
    if os.path.exists(dest) and dest.endswith('.tex'):
        with open(dest, encoding = 'utf-8') as f:
            head = f.read(4096)
        if BANNER_MARK not in head:
            keep = os.path.join(C.PAPERDIR, 'superseded', os.path.basename(dest))
            os.makedirs(os.path.dirname(keep), exist_ok = True)
            shutil.copy2(dest, keep)
            report.append('  kept the hand-written {} as {}'.format(
                os.path.basename(dest), os.path.relpath(keep, C.REPO)))
    shutil.copy2(src, dest)


def build(name, copy = True, report = None):
    kind, fn, rel = OUTPUTS[name]
    report = [] if report is None else report
    if kind == 'table':
        text = fn()
        os.makedirs(os.path.join(C.PAPERDIR, 'Tables'), exist_ok = True)
        src = os.path.join(C.PAPERDIR, 'Tables', os.path.basename(rel))
        with open(src, 'w', encoding = 'utf-8') as f:
            f.write(text)
        built = [src]
    else:
        built = fn()
        src = [p for p in built if p.endswith('.pdf')][0]
    if copy and name not in ONLINE_ONLY:
        _copy(src, os.path.join(C.PAPERTEX, rel), report)
    return built, rel


MAP_FILE = os.path.join(C.REPO, 'REPLICATION.md')
MAP_BEGIN, MAP_END = '<!-- outputs:begin -->', '<!-- outputs:end -->'


def _traceInputs(fn):
    """ Run one builder with pandas' file readers wrapped, and return the repo-relative paths it read.
    Every csv a builder uses goes through pd.read_csv, so the trace is the builder's input list; a figure
    builder also writes its files to results/paper, as --list does. """
    import pandas as pd
    seen, orig = [], (pd.read_csv, pd.read_excel)

    def wrap(f):
        def g(path, *a, **k):
            if isinstance(path, (str, os.PathLike)):
                seen.append(os.path.abspath(os.fspath(path)))
            return f(path, *a, **k)
        return g
    pd.read_csv, pd.read_excel = wrap(orig[0]), wrap(orig[1])
    try:
        fn()
    finally:
        pd.read_csv, pd.read_excel = orig
    root = os.path.abspath(C.REPO)
    return sorted({os.path.relpath(p, root).replace(os.sep, '/') for p in seen if p.startswith(root)})


def _compress(paths):
    """ Paths that differ only in a rho value collapse into one `rho*` pattern with a file count. """
    import re
    groups = {}
    for p in paths:
        groups.setdefault(re.sub(r'rho\d+\.\d+', 'rho*', p), []).append(p)
    return ', '.join('`{}`'.format(pat) + (' ({} files)'.format(len(ps)) if len(ps) > 1 else '')
                     for pat, ps in groups.items())


def _usedIn():
    """ {path as the paper's tex writes it: [tex files, relative to writing/Paper, that input it]}. """
    import re
    uses = {}
    for d, dirs, files in os.walk(C.PAPERTEX):
        dirs[:] = [x for x in dirs if x not in ('Tables', 'exports')]
        for f in files:
            if not f.endswith('.tex'):
                continue
            p = os.path.join(d, f)
            with open(p, encoding = 'utf-8', errors = 'replace') as fh:
                text = fh.read()
            rel = os.path.relpath(p, C.PAPERTEX).replace(os.sep, '/')
            for m in re.finditer(r'\\(?:input|includegraphics)\s*(?:\[[^\]]*\])?\s*\{([^}]*)\}', text):
                uses.setdefault(m.group(1).strip(), []).append(rel)
    return uses


def writeMap():
    """ The output map of REPLICATION.md: one row per registered output, with the files it reads (traced,
    not declared) and the tex files that input it. Rewritten between MAP_BEGIN/MAP_END; printed when the
    markers are missing. """
    uses = _usedIn()
    rows = ['| Output | Kind | File in `writing/Paper` | Reads | Input by |', '|---|---|---|---|---|']
    for name, (kind, fn, rel) in OUTPUTS.items():
        try:
            reads = _compress(_traceInputs(fn))
        except D.MissingInput as e:
            reads = 'BLOCKED: {}'.format(e)
        where = uses.get(rel, []) + uses.get(os.path.splitext(rel)[0], [])
        if name in ONLINE_ONLY:
            rows.append('| `{}` | {} | online appendix only | {} | -- |'.format(name, kind, reads))
            continue
        rows.append('| `{}` | {} | `{}` | {} | {} |'.format(
            name, kind, rel, reads, ', '.join('`{}`'.format(w) for w in where) or 'online appendix'))
    block = ('{}\n{} outputs, generated by `python\\paper\\build.py --map` on {}. Reads are traced at build '
             'time, `rho*` standing for the files of a rho grid. Every output is shown in the online appendix '
             '(`writing/OnlineAppendix`); "online appendix" marks one the paper does not input, and "online '
             'appendix only" one that is not copied into `writing/Paper` at all.\n\n{}\n{}'
             .format(MAP_BEGIN, len(OUTPUTS), datetime.date.today().isoformat(), '\n'.join(rows), MAP_END))
    if not os.path.exists(MAP_FILE):
        print(block)
        return
    with open(MAP_FILE, encoding = 'utf-8') as f:
        text = f.read()
    i, j = text.find(MAP_BEGIN), text.find(MAP_END)
    if i < 0 or j < 0:
        print(block)
        return
    with open(MAP_FILE, 'w', encoding = 'utf-8', newline = '\n') as f:
        f.write(text[:i] + block + text[j + len(MAP_END):])
    print('map written: {} ({} outputs)'.format(os.path.relpath(MAP_FILE, C.REPO), len(OUTPUTS)))


def main():
    p = argparse.ArgumentParser(description = __doc__.split('\n')[1])
    p.add_argument('--only', nargs = '+', choices = list(OUTPUTS), default = list(OUTPUTS))
    p.add_argument('--copy', dest = 'copy', action = 'store_true', default = True,
                   help = 'copy into writing/Paper (the default)')
    p.add_argument('--no-copy', dest = 'copy', action = 'store_false',
                   help = 'write results/paper only, leaving writing/Paper untouched')
    p.add_argument('--list', action = 'store_true', help = 'report buildability and exit')
    p.add_argument('--map', action = 'store_true', help = 'rewrite the output map in REPLICATION.md and exit')
    p.add_argument('--site', action = 'store_true',
                   help = 'write the online appendix from results/paper (onlineAppendix.build) and exit')
    a = p.parse_args()
    if a.map:
        writeMap()
        return
    if a.site:
        try:
            import onlineAppendix          # lazily: the paper build never needs it
        except ModuleNotFoundError as e:
            if e.name != 'onlineAppendix':
                raise
            print('--site: python/paper/onlineAppendix.py is missing; the online appendix cannot be built.')
            sys.exit(1)
        onlineAppendix.build()
        return

    built, skipped, report = [], [], []
    for name in a.only:
        kind, fn, rel = OUTPUTS[name]
        if a.list:
            try:
                fn()                      # cheap; the loaders raise before any real work
                print('{:<22} {:<7} OK'.format(name, kind))
            except D.MissingInput as e:
                print('{:<22} {:<7} BLOCKED -- {}'.format(name, kind, e))
            continue
        try:
            paths, rel = build(name, a.copy, report)
            built.append((name, rel, paths))
            print('built  {:<22} -> {}'.format(name, rel if a.copy and name not in ONLINE_ONLY else
                                               os.path.relpath(paths[0], C.REPO)))
        except D.MissingInput as e:
            skipped.append((name, str(e)))
            print('SKIP   {:<22} {}'.format(name, e))

    if a.list:
        return
    for line in report:
        print(line)
    print('\n{} built, {} skipped{}.'.format(len(built), len(skipped),
                                             '' if a.copy else ' (not copied: --no-copy)'))
    if skipped:
        print('Run the missing experiments with one of:')
        print('  .venv\\Scripts\\python.exe python\\paper\\runShocks.py      (Argentina)')
        print('  .venv\\Scripts\\python.exe python\\paper\\runShocksUS.py    (US / France / UK)')
        print('...and if a calibration is what is missing, the matching runCalibration*.py first.')
        for name, why in skipped:
            print('  {:<22} {}'.format(name, why))


if __name__ == '__main__':
    main()
