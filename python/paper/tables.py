r""" Table builders. Each returns the complete tex body of one file in writing/Paper/Tables/.

The generated tex reproduces the STRUCTURE of the hand-written table it replaces (threeparttable,
booktabs rules, the same caption, label and notes), so the paper's \ref{}s keep resolving and a diff
against the previous version shows moved numbers rather than a re-layout. Only the numbers come from
results/.

Every body row ends with ` % row: <key>` (rowKey, keyed), the row's `data-row` in the online appendix's
HTML (texTable). Deleting those comments gives back the table as LaTeX sees it.
"""
import numpy as np, pandas as pd

import config as C
import datasets as D

BANNER = ('%% GENERATED by python/paper/build.py from results/ -- do not edit by hand.\n'
          '%% Rebuild:  .venv\\Scripts\\python.exe python\\paper\\build.py --only {name}\n'
          '%% Source:   {src}\n')

LQ, RQ = '``', "''"      # tex quotation marks, kept out of the string literals below


def rowKey(block, rho = None, effect = None):
    """ The `% row:` key of one body row, `<block>[@<rho>][@<effect>]`: `block` lowercase ASCII (or a
    parameter name), rho to one decimal, effect 'full' or 'ee'. """
    return (block + ('' if rho is None else '@{:.1f}'.format(float(rho)))
            + ('' if effect is None else '@' + effect))


def keyed(line, key):
    r""" `line` with ` % row: <key>` appended. It must be the LAST thing on the line: any row spacing
    (`[1.25ex]`, `\hline`, `[.5em]\hline\\[-.75em]`) goes on before it, or it ends up inside the comment.
    `key` None leaves the line alone (header rows, block titles, rules, commented-out rows). """
    return line if key is None else line + ' % row: ' + key


def notesBlock(note):
    r""" The tablenotes block.

    A single unlabelled note is set flush left with no list indentation -- it is a paragraph, not a list
    of one. A note that carries labelled markers keyed to table cells stays a list, so
    the markers keep their hanging indent. """
    if not note:
        return ''
    note = note.strip()
    if note.startswith(r'\item '):
        note = note[len(r'\item '):]
    if r'\item[' in note:
        return '\\begin{tablenotes}\n\\footnotesize\n\\item ' + note + '\n\\end{tablenotes}\n'
    return '\\begin{tablenotes}[flushleft]\n\\footnotesize\n\\item[] ' + note + '\n\\end{tablenotes}\n'


def _wrap(name, src, caption, label, colspec, header, rows, note, keys):
    """ One threeparttable. `rows` is a list of already-formatted cell lists, `keys` their row keys
    (None for a commented-out row). """
    body = '\n'.join(keyed(' & '.join(r) + r' \\[1ex]', k) for r, k in zip(rows, keys, strict = True))
    return (BANNER.format(name = name, src = src)
            + '\\begin{table}[!htb]\n\\centering\n\\begin{threeparttable}\n'
            + '\\caption{' + caption + '}\n\\label{' + label + '}\n'
            + '\\begin{tabular}{' + colspec + '}\n\\toprule\n'
            + ' & '.join(header) + ' \\\\\n\\midrule \n'
            + body + '\n\\bottomrule\n\\end{tabular}\n'
            + notesBlock(note)
            + '\\end{threeparttable}\n\\end{table}\n')


